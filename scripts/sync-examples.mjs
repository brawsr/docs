import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const execFileAsync = promisify(execFile);
const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const lockPath = path.join(repoRoot, "examples.lock.json");
const args = process.argv.slice(2);
const write = args.includes("--write");
const check = args.includes("--check");
const sourceIndex = args.indexOf("--source");
const sourceRoot =
  sourceIndex === -1 ? undefined : path.resolve(args[sourceIndex + 1] ?? "");

if (write === check)
  throw new Error("Choose exactly one of --write or --check");
if (write && !sourceRoot)
  throw new Error("--write requires --source <examples checkout>");
if (sourceIndex !== -1 && !args[sourceIndex + 1]) {
  throw new Error("--source requires a checkout path");
}

const lock = JSON.parse(await readFile(lockPath, "utf8"));

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

function digest(content) {
  return createHash("sha256").update(content).digest("hex");
}

function snapshotPath(sourcePath) {
  return path.join(repoRoot, "examples-source", sourcePath);
}

function pagePath(slug) {
  return path.join(repoRoot, "content", "docs", "examples", `${slug}.mdx`);
}

function sourceUrl(sourcePath) {
  return `https://github.com/${lock.repository}/blob/${lock.commit}/${sourcePath}`;
}

function renderPage(page, sources) {
  const renderedSources = page.sources
    .map((source, index) => {
      const heading =
        page.sources.length === 1
          ? "## Source"
          : `## ${path.basename(source.path)}`;
      return `${heading}

[View the pinned file on GitHub](${sourceUrl(source.path)}) · SHA-256 \`${source.sha256}\`

\`\`\`${source.language}
${sources[index].toString("utf8").trimEnd()}
\`\`\``;
    })
    .join("\n\n");

  return `---
title: ${JSON.stringify(page.title)}
description: ${JSON.stringify(page.description)}
---

{/* Generated by scripts/sync-examples.mjs. Edit brawsr/examples, not this page. */}

<Callout type="info" title="Pinned executable source">
  The code below is synchronized from [\`${lock.repository}\`](https://github.com/${lock.repository})
  at commit [\`${lock.commit.slice(0, 7)}\`](https://github.com/${lock.repository}/commit/${lock.commit}).
  CI verifies both the commit and each file hash.
</Callout>

${page.intro}

## Get the example

\`\`\`bash
git clone https://github.com/${lock.repository}.git
cd examples
git checkout ${lock.commit}
\`\`\`

## Install

\`\`\`bash
${page.install}
\`\`\`

${renderedSources}

## Run

Run from the repository root:

\`\`\`bash
${page.run}
\`\`\`

${page.success}

<Cards>
  <Card title="All examples" href="/docs/examples" />
  <Card title="API and SDK guide" href="/docs/guides/api-and-sdk" />
  <Card title="Recovery limitations" href="/docs/guides/recovery-limitations" />
</Cards>
`;
}

invariant(lock.schemaVersion === 1, "Unsupported examples lock schema");
invariant(
  lock.repository === "brawsr/examples",
  "Unexpected examples repository",
);
invariant(
  /^[0-9a-f]{40}$/.test(lock.commit),
  "Examples lock must use a full commit SHA",
);
invariant(
  Array.isArray(lock.pages) && lock.pages.length > 0,
  "Examples lock has no pages",
);

const slugs = new Set();
const sourceHashes = new Map();
let sourceCommit;
if (sourceRoot) {
  ({ stdout: sourceCommit } = await execFileAsync("git", [
    "-C",
    sourceRoot,
    "rev-parse",
    "HEAD",
  ]));
  sourceCommit = sourceCommit.trim();
  if (write) lock.commit = sourceCommit;
  else
    invariant(
      sourceCommit === lock.commit,
      `Examples checkout is ${sourceCommit}, expected ${lock.commit}`,
    );
}

for (const page of lock.pages) {
  invariant(
    typeof page.slug === "string" && /^[a-z0-9-]+$/.test(page.slug),
    "Invalid example slug",
  );
  invariant(!slugs.has(page.slug), `Duplicate example slug: ${page.slug}`);
  slugs.add(page.slug);
  invariant(
    Array.isArray(page.sources) && page.sources.length > 0,
    `${page.slug} has no sources`,
  );

  const snapshots = [];
  for (const source of page.sources) {
    invariant(
      !path.isAbsolute(source.path) && !source.path.includes(".."),
      `Unsafe source path: ${source.path}`,
    );
    let snapshot;
    if (write) {
      snapshot = await readFile(path.join(sourceRoot, source.path));
      await mkdir(path.dirname(snapshotPath(source.path)), { recursive: true });
      await writeFile(snapshotPath(source.path), snapshot);
      source.sha256 = digest(snapshot);
    } else {
      snapshot = await readFile(snapshotPath(source.path));
    }

    invariant(
      digest(snapshot) === source.sha256,
      `Snapshot hash mismatch: ${source.path}`,
    );
    const priorHash = sourceHashes.get(source.path);
    invariant(
      !priorHash || priorHash === source.sha256,
      `Conflicting lock entries: ${source.path}`,
    );
    sourceHashes.set(source.path, source.sha256);

    if (sourceRoot && !write) {
      const upstream = await readFile(path.join(sourceRoot, source.path));
      invariant(
        upstream.equals(snapshot),
        `Pinned source drift: ${source.path}`,
      );
    }
    snapshots.push(snapshot);
  }

  const rendered = renderPage(page, snapshots);
  if (write) {
    await mkdir(path.dirname(pagePath(page.slug)), { recursive: true });
    await writeFile(pagePath(page.slug), rendered);
  } else {
    invariant(
      (await readFile(pagePath(page.slug), "utf8")) === rendered,
      `Generated page drift: ${page.slug}`,
    );
  }
}

if (write) await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);

console.log(
  `${write ? "synchronized" : "verified"} ${lock.pages.length} pages from ${sourceHashes.size} files at ${lock.commit}`,
);
